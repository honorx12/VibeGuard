#!/usr/bin/env python3
"""Build and validate the local skill catalogue and coverage map document.

  python scripts/build_registry.py            # (re)write registry/skills-index.json and docs/COVERAGE_MAP.md
  python scripts/build_registry.py --check    # exit 1 if committed files are stale or invalid

Only first-party skills in skills/ are indexed here. Third-party candidates live in
registry/external-candidates.json (created by scripts/discover_skills.py) and are
validated, never installed or executed.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_skills as vs  # noqa: E402

GENERATED_BY = "scripts/build_registry.py"

def build_entries(root: Path, existing: dict, today: str):
    entries = []
    for f in vs.find_skill_files(root / "skills"):
        fm, _ = vs.parse_frontmatter(f.read_text(encoding="utf-8"))
        name = fm["name"]
        meta = fm.get("metadata", {})
        _, body = vs.parse_frontmatter(f.read_text(encoding="utf-8"))
        import re
        m = re.search(r"^## Related Skills\s*\n(.*?)(?=^## |\Z)", body, re.M | re.S)
        related = sorted(re.findall(r"`([^`]+)`", m.group(1))) if m else []
        entry = {
            "id": f"local/{name}", "name": name, "description": fm["description"],
            "category": meta.get("category", "engineering"),
            "source_url": str(f.relative_to(root)).replace("\\", "/"), "repository_url": None,
            "revision": meta.get("version", "unversioned"), "license": fm.get("license", "UNKNOWN"),
            "compatibility": ["agentskills.io-spec"], "last_reviewed": None,
            "review_status": "first-party",
            "risk_notes": "First-party content; still requires human review before use. Contains instructions only, no executable code.",
            "related_skills": related, "redistribution": "own-content",
        }
        old = existing.get(entry["id"])
        stripped = lambda e: {k: v for k, v in e.items() if k != "last_reviewed"}
        entry["last_reviewed"] = old["last_reviewed"] if old and stripped(old) == stripped(entry) and old.get("last_reviewed") else today
        entries.append(entry)
    return sorted(entries, key=lambda e: e["id"])

def render_coverage_map(cov: dict) -> str:
    titles = {"security": "Security issues (70)", "ux": "Website UX enhancements (20)", "production": "Production-readiness checklist (20 requested + 7 extensions)"}
    out = ["# Coverage Map", "",
           "<!-- GENERATED by scripts/build_registry.py from registry/coverage.json. Do not edit by hand. -->", "",
           "Every item maps to a primary skill (which documents detection, fix and verification under the same ID) and optional supporting skills.",
           "Mapping an item to a skill means guidance exists; it does not mean any specific project is protected or compliant.", ""]
    for group in ("security", "ux", "production"):
        out += [f"## {titles[group]}", "", "| ID | Item | Primary skill | Supporting skills | Verification (summary) |", "| --- | --- | --- | --- | --- |"]
        for it in cov[group]:
            sup = ", ".join(f"`{s}`" for s in it["secondary_skills"]) or "-"
            ver = it["verification"].replace("|", "\\|")
            out.append(f"| {it['id']} | {it['title']} | `{it['primary_skill']}` | {sup} | {ver} |")
        out.append("")
    return "\n".join(out)

def build(root: Path, today: str):
    idx_path = root / "registry" / "skills-index.json"
    existing = {}
    if idx_path.exists():
        try:
            existing = {s["id"]: s for s in json.loads(idx_path.read_text())["skills"]}
        except (json.JSONDecodeError, KeyError):
            existing = {}
    index = {"schema_version": 1, "generated_by": GENERATED_BY, "skills": build_entries(root, existing, today)}
    cov = json.loads((root / "registry" / "coverage.json").read_text(encoding="utf-8"))
    return index, render_coverage_map(cov)

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--check", action="store_true", help="verify committed outputs are current; write nothing")
    ap.add_argument("--today", default=dt.date.today().isoformat(), help="date used for new last_reviewed values")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    index, cov_md = build(root, args.today)
    idx_text = json.dumps(index, indent=2, ensure_ascii=False) + "\n"
    idx_path, md_path = root / "registry" / "skills-index.json", root / "docs" / "COVERAGE_MAP.md"
    if args.check:
        bad = []
        if not idx_path.exists() or idx_path.read_text(encoding="utf-8") != idx_text: bad.append(str(idx_path.relative_to(root)))
        if not md_path.exists() or md_path.read_text(encoding="utf-8") != cov_md + "\n": bad.append(str(md_path.relative_to(root)))
        if bad:
            print("STALE: run `python scripts/build_registry.py` to regenerate: " + ", ".join(bad)); return 1
        errs = vs.validate_registry(root / "registry")
        if errs:
            print("INVALID registry:"); [print("  -", e) for e in errs]; return 1
        print("OK: registry and coverage map are current and valid"); return 0
    md_path.parent.mkdir(exist_ok=True)
    idx_path.write_text(idx_text, encoding="utf-8")
    md_path.write_text(cov_md + "\n", encoding="utf-8")
    errs = vs.validate_registry(root / "registry")
    if errs:
        print("Registry written but INVALID:"); [print("  -", e) for e in errs]; return 1
    print(f"Wrote {idx_path.relative_to(root)} ({len(index['skills'])} skills) and {md_path.relative_to(root)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
